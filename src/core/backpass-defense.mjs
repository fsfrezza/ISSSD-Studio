// Native targets: 84:E4FE (wall) and 84:E578 (other defenders).
// Only the private backpass, state 5, within the strict penalty-spot distance
// uses these adjustments. Central wall targets retain the approved v2 path.
import {BACKPASS_STATE} from './experimental-backpass-penalty.mjs';
const WALL_MARKER=BACKPASS_STATE+18,NEAR_GOAL=BACKPASS_STATE+20;
const long=n=>[n&255,n>>8&255,n>>16&255];
function code(){const b=[],l={},r=[];return{e(...v){b.push(...v)},label(n){l[n]=b.length},br(op,n){b.push(op,0);r.push([b.length-1,n])},end(){for(const[a,n]of r){let d=l[n]-a-1;if(d< -128||d>127)throw Error('range '+n+' '+d);b[a]=d&255}return Uint8Array.from(b)}}}
export const DEFENSE_CENTER=0xFFF620,DEFENSE_WALL=0xFFF480,DEFENSE_KEEPER=0xFFF680;
const lateral=DEFENSE_CENTER;
// World-coordinate posts are center +/-48. Reserve eight units at each post;
// with n members, halfSpan=6*(n-1), center=clamp(ballSide/4, +/-(40-halfSpan)).
// A defending keeper takes the complementary side, 24 units inside the field.
// This depth also exceeds the native arrival tolerance seen in the matrix.
export function backpassDefenseCenter(){const c=code(),e=(...v)=>c.e(...v);
 // Six-unit half spans give twelve-unit spacing for all native 1..6 walls.
 e(0xAF,...long(0x11F6),0x0A,0x85,0x40,0x0A,0x18,0x65,0x40,0x85,0x40,0xA9,40,0,0x38,0xE5,0x40,0x85,0x42);
 e(0xAF,...long(0x11F2),0x38,0xEF,...long(0x12D8));
 for(let i=0;i<2;i++)e(0xC9,0,0x80,0x6A);
 c.br(0x30,'negative');e(0xC5,0x42);c.br(0x90,'done');e(0xA5,0x42);c.br(0x80,'done');
 c.label('negative');e(0x49,255,255,0x1A,0xC5,0x42);c.br(0x90,'negate');e(0xA5,0x42);c.label('negate');e(0x49,255,255,0x1A);
 c.label('done');e(0x85,0x44,0x6B);return c.end();}
